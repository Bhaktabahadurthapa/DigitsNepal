<section class="wrap prose privacy">
  <div class="reveal">
    <h2>The app &amp; DigitsNepalAI</h2>
    <ul>
      <li><b>No account, no analytics, no telemetry.</b> DigitsNepal never phones home.</li>
      <li><b>Local by default.</b> DigitsNepalAI starts on a model running on your own Mac (Ollama). Your text never leaves your computer.</li>
      <li><b>Cloud only when you say so.</b> If you choose a cloud provider, text you translate is sent to that provider — and only after you switch on permission for that specific provider.</li>
      <li><b>Keys in the Keychain.</b> API keys are stored in the macOS Keychain, never in plain files, logs or the app's interface.</li>
      <li><b>No keylogging.</b> DigitsNepal only sees text you type into it, or text you select and send with <kbd>⌃⌥T</kbd>. Password fields are refused.</li>
      <li><b>Clipboard on request.</b> Read only when you click a clearly labelled button; written only when you press Copy.</li>
      <li><b>History is off by default</b>, stored only on your Mac when you turn it on, and deletable at any time.</li>
      <li><b>Hide in share</b> asks macOS to leave DigitsNepal out of screen sharing and recordings.</li>
    </ul>
  </div>
  <div class="reveal">
    <h2>This website</h2>
    <ul>
      <li>No cookies, no analytics, no ads, no trackers.</li>
      <li>Fonts and images are served from this domain — your browser doesn't contact Google or anyone else to show these pages.</li>
      <li>The dictionary runs entirely in your browser; nothing you type into it is sent.</li>
      <li>Release information is fetched from GitHub by our server, not by your browser.</li>
      <li>Our host keeps standard server logs (such as IP address and pages requested) for security and reliability.</li>
    </ul>
  </div>
