<?php
declare(strict_types=1);

/** HTML-escape for text and attribute contexts. */
function e(?string $s): string
{
    return htmlspecialchars((string) $s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/** Site-relative URL that works at the domain root or in a sub-folder. */
function url(string $path = ''): string
{
    return BASE . '/' . ltrim($path, '/');
}

/** Western digits → Devanagari digits (0-9 → ०-९). */
function deva_digits(string $s): string
{
    return strtr($s, ['0' => '०', '1' => '१', '2' => '२', '3' => '३', '4' => '४', '5' => '५', '6' => '६', '7' => '७', '8' => '८', '9' => '९']);
}

function human_size(int $bytes): string
{
    if ($bytes >= 1048576) {
        return number_format($bytes / 1048576, 1) . ' MB';
    }
    return number_format(max(1, (int) round($bytes / 1024))) . ' KB';
}

function nice_date(string $iso): string
{
    $t = strtotime($iso);
    return $t ? date('j F Y', $t) : '';
}

