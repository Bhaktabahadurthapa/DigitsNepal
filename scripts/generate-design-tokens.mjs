const typeScale = Object.entries(type)
  .map(([k, e]) => `  --text-${k}: ${Math.round(base * ratio ** e * 2) / 2}px;`)
  .join("\n");

const space = [0, 4, 8, 12, 16, 24, 32, 48, 64];
const spacing = space.map((v, i) => `  --space-${i}: ${v}px;`).join("\n");

