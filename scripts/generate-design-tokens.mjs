// DigitsNepal design tokens: generated from one brand color.
// Usage: node scripts/generate-design-tokens.mjs [#brand] > src/styles/tokens.css
// Produces a 50–900 brand scale, neutral greys, semantic colors (light + dark),
// Light is the default theme; dark applies with data-theme="dark" or
// data-theme="system" + macOS Dark Mode.
// a ×1.2 modular type scale, an 8-point spacing grid, radii, shadows, motion.

const brand = (process.argv[2] || "#0A6CFF").toLowerCase();

function hexToHsl(hex) {
  const n = parseInt(hex.slice(1), 16);
  let r = (n >> 16) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0;
  const l = (max + min) / 2;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h /= 6;
  }
  return [h * 360, s * 100, l * 100];
}
const hsl = (h, s, l) => `hsl(${h.toFixed(1)} ${s.toFixed(1)}% ${l.toFixed(1)}%)`;

const [h, s] = hexToHsl(brand);
// Lightness ramp tuned so 500 ≈ the brand color and 600+ passes 4.5:1 on white.
const steps = { 50: 97, 100: 93, 200: 86, 300: 75, 400: 62, 500: 52, 600: 45, 700: 38, 800: 30, 900: 22 };
const scale = Object.entries(steps).map(([k, l]) => `  --brand-${k}: ${hsl(h, Math.min(100, s), l)};`).join("\n");

